    LOCAL, 
    COUNT(*) AS TOTAL_JOGOS,
    AVG(MANDANTEGOLS + VISITANTEGOLS) AS MEDIA_GOLS
FROM TBRAS
GROUP BY LOCAL
ORDER BY MEDIA_GOLS DESC;

-- DESVIO PADRAO DE GOL EM CADA ESTÁDIO

SELECT 
    LOCAL, 
    COUNT(*) AS TOTAL_JOGOS,
    AVG(MANDANTEGOLS + VISITANTEGOLS) AS MEDIA_GOLS,
    STD(MANDANTEGOLS + VISITANTEGOLS) AS DESVIO_PADRAO
FROM TBRAS
GROUP BY LOCAL
ORDER BY DESVIO_PADRAO DESC;






